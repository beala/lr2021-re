# Writes fft_tables.h: 256-point FFT twiddles (cos, -sin) and half a Hann window, Q15.
import math, os
N = 256
tw = [(round(math.cos(2 * math.pi * k / N) * 32767), round(-math.sin(2 * math.pi * k / N) * 32767)) for k in range(N // 2)]
win = [round((0.5 - 0.5 * math.cos(2 * math.pi * n / N)) * 32767) for n in range(N // 2)]
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'fft_tables.h'), 'w') as f:
    f.write('// Generated by gen_tables.py: 256-point FFT twiddles (cos, -sin) and half a Hann window, Q15.\n')
    f.write('static const short TW[128][2] = {\n' + ',\n'.join(f'  {{{c}, {s}}}' for c, s in tw) + '\n};\n')
    f.write('static const short WIN[128] = {\n  ' + ', '.join(map(str, win)) + '\n};\n')
